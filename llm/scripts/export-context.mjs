// 운영 챗봇(api/src/context.js)과 같은 시스템 프롬프트를 학습·평가용으로 내보낸다.
// 문맥을 따로 만들지 않고 buildSystemPrompt() 를 그대로 호출하므로 전화번호 제외·draft 사례 처리 규칙이 운영과 같다.
//
// 사용: node llm/scripts/export-context.mjs   (저장소 루트에서, Node 18+)
// 출력: llm/data/generated/context.json
//   - system_prompt: Gemini 에 보내는 것과 같은 시스템 프롬프트 (행동 규칙 + 이력 문맥)
//   - foreign: 외국어 질문일 때 index.js 가 덧붙이는 지시문 (index.js 와 다르면 실패)
//   - resume: 출처(source_refs) 검증용 공개 이력 데이터 (contact.phone 제외)
//   - projects: 프로젝트 id·이름·draft 사례 목록 (관련: 줄 검사용)
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import resume from "../../src/data/resume.js";
import { buildSystemPrompt } from "../../api/src/context.js";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const OUT = join(ROOT, "llm", "data", "generated", "context.json");

// api/src/index.js 의 외국어 질문 처리 문구. 운영과 같은 입력을 만들려고 복사해 두고, 원본에 그대로 있는지 확인한다.
const FOREIGN_EXTRA_SYSTEM =
  "\n\n[이번 질문의 언어]\n방문자가 한국어가 아닌 언어로 질문했습니다. 답변 본문은 반드시 질문과 같은 언어로 씁니다(한국어로 쓰지 않습니다). \"관련:\"과 \"다음:\" 머리말만 한국어로 둡니다.";
const FOREIGN_QUESTION_PREFIX =
  "Answer in the same language as the question below (do NOT answer in Korean). Keep only the '관련:' and '다음:' labels in Korean.\n\n";

const sha256 = text => createHash("sha256").update(text).digest("hex");
const rel = p => relative(ROOT, p).split("\\").join("/");

function fail(msg) {
  console.error(`export-context: ${msg}`);
  process.exit(1);
}

const indexPath = join(ROOT, "api", "src", "index.js");
const indexSrc = readFileSync(indexPath, "utf8");
for (const [name, value] of [["FOREIGN_EXTRA_SYSTEM", FOREIGN_EXTRA_SYSTEM], ["FOREIGN_QUESTION_PREFIX", FOREIGN_QUESTION_PREFIX]]) {
  if (!indexSrc.includes(JSON.stringify(value))) {
    fail(`${name} 문구가 api/src/index.js 에 없습니다. index.js 의 외국어 처리 문구가 바뀌었으면 이 파일의 값도 맞춰 주세요.`);
  }
}
if (!indexSrc.includes("const foreign = Boolean(question) && !/[가-힣]/.test(question);")) {
  fail("api/src/index.js 의 외국어 판별식이 바뀌었습니다. llm/common.py 의 is_foreign() 도 함께 확인해 주세요.");
}

const systemPrompt = buildSystemPrompt();
const phone = resume.contact?.phone;
if (phone && systemPrompt.includes(phone)) fail("시스템 프롬프트에 전화번호가 들어 있습니다.");

// 출처 검증용 공개 데이터: 전화번호만 뺀다 (챗봇 문맥과 같은 공개 범위)
const { phone: _omit, ...publicContact } = resume.contact || {};
const publicResume = { ...resume, contact: publicContact };

// AskMe.jsx 의 PROJECT_NAMES 와 같은 규칙으로 화면 표시 이름을 만든다
const shortName = p => p.name.split(" - ")[0].replace(/\s*\(.*\)$/, "");
const projects = [
  ...resume.projects.map(p => ({ ...p, kind: "company" })),
  ...(resume.sideProjects || []).map(p => ({ ...p, kind: "side" })),
].map(p => ({
  id: p.id,
  name: p.name,
  short_name: shortName(p),
  kind: p.kind,
  period: p.period,
  draft_cases: (p.cases || []).map((c, i) => (c.draft ? i : null)).filter(i => i !== null),
}));

const sources = ["src/data/resume.js", "api/src/context.js", "api/src/index.js"];
const out = {
  note: "generated by llm/scripts/export-context.mjs - 직접 수정하지 마세요",
  source_sha256: Object.fromEntries(sources.map(p => [p, sha256(readFileSync(join(ROOT, p), "utf8"))])),
  system_prompt: systemPrompt,
  system_prompt_sha256: sha256(systemPrompt),
  system_prompt_chars: systemPrompt.length,
  foreign: {
    detect: "질문에 한글([가-힣])이 하나도 없으면 외국어 질문 (api/src/index.js 와 같은 기준)",
    extra_system: FOREIGN_EXTRA_SYSTEM,
    question_prefix: FOREIGN_QUESTION_PREFIX,
  },
  projects,
  resume: publicResume,
};

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, JSON.stringify(out, null, 2) + "\n");
console.log(`wrote ${rel(OUT)}`);
console.log(`  system prompt: ${systemPrompt.length} chars, sha256 ${out.system_prompt_sha256.slice(0, 12)}`);
console.log(`  projects: ${projects.map(p => p.id).join(", ")}`);
console.log(`  draft cases: ${projects.filter(p => p.draft_cases.length).map(p => `${p.id}${JSON.stringify(p.draft_cases)}`).join(", ") || "없음"}`);
